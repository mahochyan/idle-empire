'use strict';
// Restore real alloy losses after the paid core-farming encounters.
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const fs=require('node:fs');
const path=require('node:path');
const {environment}=require('../../tests/progression/harness');
const root=path.resolve(__dirname,'../..');
const input=process.argv.find(x=>x.startsWith('--input='))?.slice('--input='.length)||'p277-awakening-core-rifle2-2-paid-save.json';
const label=process.argv.find(x=>x.startsWith('--label='))?.slice('--label='.length)||'rifle2-core';
const outputPrefix=process.argv.find(x=>x.startsWith('--output-prefix='))?.slice('--output-prefix='.length)||'p277';
const slot=Number(process.argv.find(x=>x.startsWith('--slot='))?.slice('--slot='.length)||2);
assert.match(input,/^p27[78]-awakening-[a-z0-9-]+\.json$/);
assert.match(label,/^[a-z0-9-]+$/);
assert.match(outputPrefix,/^p27[78]$/);
assert.ok(Number.isSafeInteger(slot)&&slot>=0&&slot<=3);
const source='docs/codex/reports/data/'+input;
const raw=fs.readFileSync(path.join(root,source),'utf8');
const sha=s=>crypto.createHash('sha256').update(s).digest('hex');
const e=environment({rts_save:raw}),run=e.run;
assert.equal(run('loadSaveAndApply().status'),'ok');
assert.equal(run(`S.formation.front[${slot}].type`),'alloy_special');
const loss=55-run(`S.formation.front[${slot}].count`);
assert.ok(Number.isSafeInteger(loss)&&loss>=1&&loss<=10);
assert.equal(run('armyCount()'),617-loss);
assert.equal(run('formSoldierCount()'),587-loss);
run(`globalThis.__RealDate=Date;globalThis.Date=class extends __RealDate {static now(){return ${JSON.parse(raw).ts}+(S.tick-${JSON.parse(raw).tick})*1000}}`);
run("globalThis.__rng=1;Math.random=()=>{let x=__rng;x^=x<<13;x^=x>>>17;x^=x<<5;__rng=x>>>0;return __rng/4294967296}");
run("globalThis.__paid={};globalThis.__basePay=payTrainingCost;payTrainingCost=(cost,n)=>{for(const[k,v]of Object.entries(cost))__paid[k]=(__paid[k]||0)+v*n;return __basePay(cost,n)}");
const queued=run(`train('alloy_special',${loss})`);assert.equal(queued?.ok,true);assert.equal(queued.qty,loss);
let seconds=0;
while(run('S.pool.alloy_special')<loss&&seconds<10){run('tick()');seconds++}
assert.equal(run('S.pool.alloy_special'),loss);
assert.deepEqual(JSON.parse(JSON.stringify(run('({...__paid})'))),{food:1500*loss,steel:100*loss});
run(`fillFormMax('expedition','front',${slot})`);
assert.equal(run(`S.formation.front[${slot}].count`),55);
assert.equal(run('armyCount()'),617);
assert.equal(run('formSoldierCount()'),587);
assert.equal(run("expeditionCount('star_trooper')"),101);
assert.equal(run('save().ok'),true);
const output=e.store.get('rts_save');
const file=`docs/codex/reports/data/${outputPrefix}-awakening-${label}-restored-save.json`;
fs.writeFileSync(path.join(root,file),output,'utf8');
const reload=environment({rts_save:output});assert.equal(reload.run('loadSaveAndApply().status'),'ok');
assert.equal(reload.run('formSoldierCount()'),587);
assert.equal(sha(fs.readFileSync(path.join(root,source),'utf8')),sha(raw));
console.log(JSON.stringify({sourceSha256:sha(raw),loss,queued,seconds,paid:run('({...__paid})'),army:run('armyCount()'),deployed:run('formSoldierCount()'),core:run('S.items.godCore'),file,saveSha256:sha(output)}));
