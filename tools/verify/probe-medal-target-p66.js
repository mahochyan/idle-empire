'use strict';
// 从同一真实郊野存档按边贸行实价兑换目标勋章；不预置兽骨或勋章。
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {environment}=require('../../tests/progression/harness');
const saveArg=process.argv.find(x=>x.startsWith('--save='));
const finalArg=process.argv.find(x=>x.startsWith('--snapshot-final='));
const targetArg=process.argv.find(x=>x.startsWith('--target='));
assert.ok(saveArg&&finalArg,'须提供 --save=档案 --snapshot-final=档案');
const target=targetArg?Number(targetArg.slice('--target='.length)):800000;
assert.ok(Number.isSafeInteger(target)&&target>0);
const raw=fs.readFileSync(saveArg.slice('--save='.length),'utf8');
const env=environment({rts_save:raw}),run=env.run;
assert.equal(run('loadSaveAndApply().status'),'ok','输入档须安全加载');
const before=run("({tick:S.tick,level:S.beastExchange.level,bone:S.res.bone,medal:S.res.medal,medalCap:resCap('medal'),techCap:resCap('tech'),scrollUsed:S.beastExchange.scrollUsed})");
assert.equal(before.level,30,'本探针只核验现有30级边贸行');
assert.ok(before.medal<target,'目标已达，不需兑换');
const costPerTrade=run('beastBoneTradeCost()'),rewardPerTrade=run('beastBoneTradeReward()');
const trades=Math.ceil((target-before.medal)/rewardPerTrade);
assert.ok(Number.isSafeInteger(trades)&&trades>0);
assert.ok(before.bone>=trades*costPerTrade,'此档兽骨不足以达到目标');
assert.ok(before.medal+trades*rewardPerTrade<=before.medalCap,'勋章仓容不足');
const result=run(`exchangeBonesForMedals(${trades})`);
assert.equal(result?.ok,true,`兽骨兑换失败：${JSON.stringify(result)}`);
assert.equal(result.boneCost,trades*costPerTrade);
assert.equal(result.medalGain,trades*rewardPerTrade);
const final=JSON.parse(env.store.get('rts_save'));
assert.equal(final.v,29);
assert.equal(final.res.bone,before.bone-result.boneCost);
assert.equal(final.res.medal,before.medal+result.medalGain);
assert.ok(final.res.medal>=target);
assert.equal(final.tick,before.tick,'兑换不推进在线时间');
assert.equal(final.beastExchange.scrollUsed,before.scrollUsed);
const reload=environment({rts_save:JSON.stringify(final)});
assert.equal(reload.run('loadSaveAndApply().status'),'ok');
assert.equal(reload.run('S.res.medal'),final.res.medal);
assert.equal(reload.run('S.res.bone'),final.res.bone);
assert.equal(reload.run("resCap('tech')"),before.techCap);
fs.writeFileSync(finalArg.slice('--snapshot-final='.length),JSON.stringify(final),'utf8');
console.log(JSON.stringify({unit:'resource units; online seconds',target,before,costPerTrade,rewardPerTrade,trades,bonePaid:result.boneCost,medalGained:result.medalGain,finish:{tick:final.tick,bone:final.res.bone,medal:final.res.medal,techCap:before.techCap,scrollUsed:final.beastExchange.scrollUsed}},null,2));
