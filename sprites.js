// ==================== 像素图标系统 ====================
// 本模块负责游戏所有像素图标的定义和渲染。
// 结构：精灵定义（字符网格→矩形） → PIX_SPRITES（32px UI图标） → MAP_SPRITES（64px 城镇建筑） → 渲染函数
// 核心思路：用字符网格定义像素画，gridToRects() 将字符网格压缩为矩形列表，spriteData() 转为内联SVG的CSS背景图。
// 五兵种精灵使用字符网格定义（约30×32），建筑物和其他UI图标使用手动矩形定义。

// 将字符网格转换为矩形列表。相邻同色字符合并为一个大矩形，减少DOM元素。
// grid: 二维字符数组，'.' 表示透明；palette: 字符→颜色映射
function gridToRects(grid,palette){
  const H=grid.length,W=grid[0].length;
  const vis=Array.from({length:H},()=>new Array(W).fill(false));
  const rects=[];
  for(let y=0;y<H;y++){
    for(let x=0;x<W;x++){
      if(vis[y][x]||grid[y][x]==='.')continue;
      const ch=grid[y][x];
      const c=palette[ch];
      if(!c)continue;
      let rw=1;
      while(x+rw<W&&grid[y][x+rw]===ch&&!vis[y][x+rw])rw++;
      let rh=1;
      while(y+rh<H){
        let ok=true;
        for(let dx=0;dx<rw;dx++){if(grid[y+rh][x+dx]!==ch||vis[y+rh][x+dx]){ok=false;break}}
        if(!ok)break;
        rh++;
      }
      for(let dy=0;dy<rh;dy++)for(let dx=0;dx<rw;dx++)vis[y+dy][x+dx]=true;
      rects.push([x,y,rw,rh,c]);
    }
  }
  return rects;
}
