// ===== 渲染函数 =====

// 将矩形数组渲染为内联 SVG 的 data URI，用作 CSS background-image
function spriteData(rects,size=32){
  const svg=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges">${rects.map(r=>`<rect x="${r[0]}" y="${r[1]}" width="${r[2]}" height="${r[3]}" fill="${r[4]}"/>`).join('')}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}
// 将 PIX_SPRITES 和 MAP_SPRITES 注入为 CSS 类（.i-xxx / .mi-xxx）
function injectPixelIcons(){
  const style=document.createElement('style');
  const uiIcons=Object.entries(PIX_SPRITES).map(([k,v])=>`.i-${k}{background-image:${spriteData(v)}}`);
  const imageIcons=Object.entries(PIX_IMAGE_SPRITES).map(([k,v])=>`.i-${k}{background-image:url("${v}");background-size:contain}`);
  const mapIcons=Object.entries(MAP_SPRITES).map(([k,v])=>`.mi-${k}{background-image:${spriteData(v,64)}}`);
  const mapImageIcons=Object.entries(MAP_IMAGE_SPRITES).map(([k,v])=>`.mi-${k}{background-image:url("${v}");background-size:contain}`);
  style.textContent=uiIcons.concat(imageIcons,mapIcons,mapImageIcons).join('\n');
  document.head.appendChild(style);
}
// 生成32px UI图标的HTML span
function pix(key, cls=''){
  return `<span class="pix-icon i-${key} ${cls}" aria-hidden="true"></span>`;
}
// 生成64px 地图建筑图标的HTML span
function mapPix(key, cls=''){
  return `<span class="map-pix mi-${key} ${cls}" aria-hidden="true"></span>`;
}
// 生成资源消耗显示；军备招募还会逐人消耗铜或铁。
function costHtml(cost){
  return ['wood','stone','food','coal','copper','iron','silver','gold','steel'].filter(rk=>Number.isFinite(cost?.[rk])&&cost[rk]>0)
    .map(rk=>`${pix(CFG.res[rk]?.icon||rk,'mini')}${cost[rk]}`).join(' ');
}
function techCostHtml(cost, needTech, needMerit, needEssence){
  let h=costHtml(cost);
  if(needTech) h+=` ${pix('tech','mini')}${needTech}`;
  if(needMerit) h+=` <span style="color:#c0a060">⚔${needMerit}</span>`;
  if(needEssence){
    const ei=CFG.essences?.[needEssence.type];
    h+=` ${pix(ei?.icon||needEssence.type,'mini')}${needEssence.count}`;
  }
  return h;
}
